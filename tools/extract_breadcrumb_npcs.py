"""Who each breadcrumb quest is about, from pfQuest's English NPC names.

A breadcrumb that's named after the NPC who gives it or the one it sends you
to (Ziz Fizziks, Malin's Request) is an errand, so a storyline it opens is
named after the quest it leads to. One with a name of its own (Taking Back
Silithus, The Spirits of Stonetalon) names the storyline itself. The client
has no way to look up an NPC's name by ID, so this writes those NPCs' names
for each breadcrumb in Data/Quests.lua to Data/BreadcrumbNPCs.lua, and the
addon compares them with the quest's title in game.

Usage:
    pip install lupa
    python3 tools/extract_breadcrumb_npcs.py        # downloads pfQuest's NPC names
    python3 tools/extract_breadcrumb_npcs.py DIR    # or uses a local copy, DIR/db_enUS_units.lua

Run it again after Data/Quests.lua gains breadcrumbs. pfQuest only has
vanilla NPCs; a breadcrumb whose NPCs it doesn't know keeps its own name.
"""

import os
import sys

from lupa import LuaRuntime

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from extract_quest_starts import ROOT, fetch, lua_string  # noqa: E402

OUT = os.path.join(ROOT, "Data", "BreadcrumbNPCs.lua")


def unit_names(local_dir):
    if local_dir:
        with open(os.path.join(local_dir, "db_enUS_units.lua"), encoding="utf-8") as f:
            src = f.read()
    else:
        src = fetch("enUS/units.lua")
    lua = LuaRuntime(unpack_returned_tuples=True, register_eval=False)
    lua.execute("pfDB = { units = {} }")
    lua.execute(src)
    return {int(k): v for k, v in lua.globals()["pfDB"]["units"]["enUS"].items() if isinstance(v, str)}


def quests():
    lua = LuaRuntime(unpack_returned_tuples=True, register_eval=False)
    ns = lua.table()
    with open(os.path.join(ROOT, "Data", "Quests.lua"), encoding="utf-8") as f:
        lua.eval("function(src, ns) return load(src)(nil, ns) end")(f.read(), ns)
    return ns.Quests


def givers(q):
    found = [q["qg"]]
    fv = q["fv"]
    if fv is not None:
        for side in (1, 2):
            if fv[side] is not None:
                found.append(fv[side]["qg"])
    return [int(g) for g in found if g is not None]


def main():
    names = unit_names(sys.argv[1] if len(sys.argv) > 1 else None)
    data = quests()
    out = {}
    unknown = 0
    for qid, q in data.items():
        if q["bc"] is None:
            continue
        npcs = givers(q)
        for nx in (q["nx"] or {}).values():
            if data[nx] is not None:
                npcs += givers(data[nx])
        known = []
        for npc in npcs:
            if npc in names and names[npc] not in known:
                known.append(names[npc])
        if known:
            out[int(qid)] = known
        else:
            unknown += 1

    lines = [
        "-- Generated by tools/extract_breadcrumb_npcs.py. Do not edit by hand.",
        "-- Source: pfQuest's database (https://github.com/shagu/pfQuest, MIT; data from VMaNGOS).",
        "-- For each breadcrumb quest, the English names of the NPC who gives it and the NPCs who",
        "-- give the quests it leads to. A breadcrumb named after one of them is an errand.",
        "local _, ns = ...",
        "ns.BreadcrumbNPCs = {",
    ]
    for qid in sorted(out):
        lines.append(f"[{qid}]={{{','.join(lua_string(n) for n in out[qid])}}},")
    lines.append("}")
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print(f"{len(out)} breadcrumbs with NPC names, {unknown} whose NPCs pfQuest doesn't know")
    print(f"Wrote {OUT}")


if __name__ == "__main__":
    main()
