#!/usr/bin/env python3
"""Build LorePath's bundled quest text from pfQuest's English quest database.

pfQuest (https://github.com/shagu/pfQuest) is MIT-licensed. Its vanilla quest
text (title, objectives, description) was extracted from the VMaNGOS project.
LorePath only uses it to fill gaps: text the game shows you while you play is
saved and always takes priority. WoW Forever's own quests aren't in pfQuest.

Usage:
    pip install lupa
    python3 tools/extract_pfquest.py            # downloads pfQuest's file
    python3 tools/extract_pfquest.py quests.lua  # or uses a local copy (the licence file isn't refreshed then)

Writes Data/QuestText.lua with entries for the quests in Data/Quests.lua only.
"""

import os
import re
import shutil
import sys
import urllib.request

from lupa import LuaRuntime

PFQUEST_RAW = "https://raw.githubusercontent.com/shagu/pfQuest/master/db/enUS/quests.lua"
PFQUEST_LICENSE = "https://raw.githubusercontent.com/shagu/pfQuest/master/LICENSE"

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))


def fetch(url):
    with urllib.request.urlopen(url, timeout=60) as response:
        return response.read().decode("utf-8")


def lua_string(text):
    """A Lua string literal for any text."""
    out = text.replace("\\", "\\\\").replace('"', '\\"').replace("\r", "").replace("\n", "\\n")
    return '"' + out + '"'


def main():
    if len(sys.argv) > 1:
        with open(sys.argv[1], encoding="utf-8") as f:
            source = f.read()
        license_text = None
    else:
        source = fetch(PFQUEST_RAW)
        license_text = fetch(PFQUEST_LICENSE)

    # Load pfQuest's table in a bare Lua state (it's a plain data file).
    lua = LuaRuntime(unpack_returned_tuples=True)
    quests = lua.execute("pfDB = { quests = {} }\n" + source + "\nreturn pfDB.quests.enUS")

    with open(os.path.join(ROOT, "Data", "Quests.lua"), encoding="utf-8") as f:
        ours = {int(m) for m in re.findall(r"^\[(\d+)\]=\{", f.read(), re.M)}

    lines = [
        "-- Generated by tools/extract_pfquest.py. Do not edit by hand.",
        "-- Quest text (title, objectives, description) from pfQuest's English database",
        "-- (https://github.com/shagu/pfQuest, MIT; see Data/pfQuest-LICENSE.txt), which",
        "-- took it from VMaNGOS. The last fallback: saved, community and quest-link text come first.",
        "-- Fields: t title, o objectives, d description. $N/$C/$R/$G/$B are filled in game.",
        "local _, ns = ...",
        "ns.QuestText = {",
    ]
    kept = 0
    for qid in sorted(ours):
        entry = quests[qid]
        if entry is None:
            continue
        parts = []
        for key, field in (("t", "T"), ("o", "O"), ("d", "D")):
            value = entry[field]
            if isinstance(value, str) and value.strip():
                parts.append(f"{key}={lua_string(value.strip())}")
        if parts:
            lines.append(f"[{qid}]={{{','.join(parts)}}},")
            kept += 1
    lines.append("}")

    out_path = os.path.join(ROOT, "Data", "QuestText.lua")
    with open(out_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    if license_text:
        with open(os.path.join(ROOT, "Data", "pfQuest-LICENSE.txt"), "w", encoding="utf-8") as f:
            f.write(license_text)

    print(f"Wrote text for {kept} of {len(ours)} LorePath quests to {out_path}")
    print(f"Size: {os.path.getsize(out_path) / 1024:.0f} KB")


if __name__ == "__main__":
    main()
