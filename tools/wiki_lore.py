#!/usr/bin/env python3
"""Zone lore from the Warcraft Wiki (issue #5).

The summaries LorePath shows at the top of a zone's page are written by hand,
from the wiki's articles, in tools/lore/zones.txt. This script does the two
mechanical parts around that:

  python3 tools/wiki_lore.py fetch [MAP_ID ...]
      Fetches the opening section of each entry's wiki article, as plain text,
      into tools/lore/raw/<map ID>.txt (not committed) to write or update the
      summary from. Says which summaries were written from an older revision
      of their article than the wiki has now, so they can be looked at again.

  python3 tools/wiki_lore.py build
      Writes Data/Lore.lua from tools/lore/zones.txt. Entries with no text yet
      are left out.

The Warcraft Wiki's text is CC BY-SA 4.0, and so are summaries made from it:
Data/Lore.lua says so in its header, and Data/WarcraftWiki-LICENSE.txt has
the notice. LorePath's code stays MIT.

zones.txt format: an entry starts with "== <map ID> <name>" (the name is for
people), then "article: <wiki page title>" and "revision: <revision ID the
summary was written from>", then a blank line, then the summary. Paragraphs
are separated by blank lines. Lines starting with "#" are comments.
"""

import json
import os
import sys
import time
import urllib.error
import urllib.parse
import urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ZONES = os.path.join(ROOT, "tools", "lore", "zones.txt")
RAW = os.path.join(ROOT, "tools", "lore", "raw")
OUT = os.path.join(ROOT, "Data", "Lore.lua")

API = "https://warcraft.wiki.gg/api.php"
# The wiki asks scripts to say who they are; requests are batched and spaced out.
USER_AGENT = "LorePath-lore-fetch/1.0 (+https://github.com/Jacob-Haynes/LorePath)"
BATCH = 20  # TextExtracts gives at most 20 extracts per request
PAUSE = 2.0  # seconds between requests


def parse_zones(text):
    """Entries in file order: {id, name, article, revision, text}."""
    entries, entry, body = [], None, []
    in_header = False

    def finish():
        if entry is not None:
            paragraphs, current = [], []
            for line in body:
                if line.strip():
                    current.append(line.strip())
                elif current:
                    paragraphs.append(" ".join(current))
                    current = []
            if current:
                paragraphs.append(" ".join(current))
            entry["text"] = "\n\n".join(paragraphs)
            entries.append(entry)

    for number, line in enumerate(text.splitlines(), 1):
        if line.startswith("#"):
            continue
        if line.startswith("== "):
            finish()
            parts = line[3:].split(None, 1)
            try:
                map_id = int(parts[0])
            except (IndexError, ValueError):
                raise SystemExit(f"zones.txt line {number}: expected '== <map ID> <name>'")
            entry, body = {"id": map_id, "name": parts[1] if len(parts) > 1 else "",
                           "article": None, "revision": None}, []
            in_header = True
            continue
        if entry is None:
            if line.strip():
                raise SystemExit(f"zones.txt line {number}: text before the first entry")
            continue
        if in_header and line.startswith("article:"):
            entry["article"] = line.split(":", 1)[1].strip()
        elif in_header and line.startswith("revision:"):
            value = line.split(":", 1)[1].strip()
            entry["revision"] = int(value) if value else None
        else:
            in_header = False
            body.append(line)
    finish()

    seen = set()
    for e in entries:
        if e["id"] in seen:
            raise SystemExit(f"zones.txt: map {e['id']} has two entries")
        seen.add(e["id"])
        if not e["article"]:
            raise SystemExit(f"zones.txt: map {e['id']} ({e['name']}) has no article")
        if e["text"] and not e["revision"]:
            raise SystemExit(f"zones.txt: map {e['id']} ({e['name']}) has text but no revision")
    return entries


def lua_string(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def render_lua(entries):
    lines = [
        "-- Generated by tools/wiki_lore.py from tools/lore/zones.txt. Do not edit by hand.",
        "-- Zone lore summarised from the Warcraft Wiki (https://warcraft.wiki.gg), whose text is",
        "-- CC BY-SA 4.0; these summaries are under the same licence (see Data/WarcraftWiki-LICENSE.txt).",
        "-- Each entry names the article it was summarised from.",
        "local _, ns = ...",
        "ns.ZoneLore = {",
    ]
    for e in sorted((e for e in entries if e["text"]), key=lambda e: e["id"]):
        lines.append(f"[{e['id']}]={{article={lua_string(e['article'])},text={lua_string(e['text'])}}},")
    lines.append("}")
    return "\n".join(lines) + "\n"


def build():
    with open(ZONES, encoding="utf-8") as f:
        entries = parse_zones(f.read())
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(render_lua(entries))
    written = sum(1 for e in entries if e["text"])
    print(f"Wrote {OUT}: {written} of {len(entries)} zones have lore.")


def api_get(params):
    params = dict(params, format="json", formatversion="2")
    url = API + "?" + urllib.parse.urlencode(params)
    request = urllib.request.Request(url, headers={"User-Agent": USER_AGENT})
    for attempt in range(4):
        try:
            with urllib.request.urlopen(request, timeout=60) as response:
                return json.load(response)
        except urllib.error.HTTPError as err:
            if err.code not in (429, 503) or attempt == 3:
                raise
            wait = int(err.headers.get("Retry-After") or 30)
            print(f"  wiki asked us to wait {wait}s")
            time.sleep(wait)


def fetch(only):
    with open(ZONES, encoding="utf-8") as f:
        entries = parse_zones(f.read())
    if only:
        entries = [e for e in entries if e["id"] in only]
    os.makedirs(RAW, exist_ok=True)
    stale = []
    for start in range(0, len(entries), BATCH):
        batch = entries[start:start + BATCH]
        if start:
            time.sleep(PAUSE)
        data = api_get({
            "action": "query", "prop": "extracts|revisions", "rvprop": "ids",
            "exintro": 1, "explaintext": 1, "exlimit": BATCH, "redirects": 1,
            "titles": "|".join(e["article"] for e in batch),
        })
        query = data.get("query", {})
        # Follow normalisation and redirects back to the title we asked for.
        renamed = {}
        for step in query.get("normalized", []) + query.get("redirects", []):
            renamed[step["from"]] = step["to"]
        pages = {p["title"]: p for p in query.get("pages", [])}
        for e in batch:
            title = e["article"]
            while title in renamed:
                title = renamed[title]
            page = pages.get(title)
            if not page or page.get("missing"):
                print(f"  {e['id']} {e['name']}: no article '{e['article']}'")
                continue
            revision = page["revisions"][0]["revid"]
            path = os.path.join(RAW, f"{e['id']}.txt")
            with open(path, "w", encoding="utf-8") as f:
                f.write(f"{e['name']}\narticle: {page['title']}\nrevision: {revision}\n"
                        f"https://warcraft.wiki.gg/wiki/{urllib.parse.quote(page['title'].replace(' ', '_'))}\n\n")
                f.write(page.get("extract", "").strip() + "\n")
            note = ""
            if e["text"] and e["revision"] != revision:
                stale.append(e)
                note = f" (summary is from revision {e['revision']})"
            print(f"  {e['id']} {e['name']}: revision {revision}{note}")
    print(f"Fetched into {RAW}.")
    if stale:
        print(f"{len(stale)} summaries were written from an older revision; compare and update them:")
        for e in stale:
            print(f"  {e['id']} {e['name']}")


def main(argv):
    if len(argv) >= 2 and argv[1] == "build" and len(argv) == 2:
        build()
    elif len(argv) >= 2 and argv[1] == "fetch":
        fetch({int(a) for a in argv[2:]})
    else:
        print(__doc__)
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
